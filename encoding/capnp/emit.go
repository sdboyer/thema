package capnp

import (
	"encoding/hex"
	"fmt"
	"strconv"
	"strings"

	"github.com/sdboyer/thema/encoding/capnp/compiled"
	"github.com/sdboyer/thema/internal/lensir"
)

// emit renders the schema as .capnp text: a file ID derived from the
// namespace and lineage, then each generation's root struct with the
// versions it reads, fields in order of first appearance, and the nodes
// nested in it after its fields. The text is deterministic: it depends only
// on the compiled nodes.
func emit(c *Compiled, gs *generations) string {
	e := &emitter{c: c}
	fmt.Fprintf(&e.b, "# Generated by thema from lineage %s. DO NOT EDIT.\n", c.Lineage)
	fmt.Fprintf(&e.b, "@%s;\n", idText(hashID(gs.ns, gs.lineage)))
	for _, g := range gs.gens {
		vs := make([]string, 0, len(g.versions))
		for _, v := range g.versions {
			vs = append(vs, v.String())
		}
		e.b.WriteString("\n")
		fmt.Fprintf(&e.b, "# %s: versions %s\n", g.root.n.Name, strings.Join(vs, ", "))
		e.node(g.root, 0)
	}
	return e.b.String()
}

type emitter struct {
	c *Compiled
	b strings.Builder
}

func (e *emitter) linef(indent int, format string, args ...any) {
	e.b.WriteString(strings.Repeat("  ", indent))
	fmt.Fprintf(&e.b, format, args...)
	e.b.WriteByte('\n')
}

// node declares a struct or enum node and, nested in a struct, its children.
func (e *emitter) node(n *gnode, indent int) {
	name := n.n.Name[strings.LastIndex(n.n.Name, ".")+1:]
	if n.n.Kind == compiled.EnumNode {
		e.linef(indent, "enum %s @%s {", name, idText(n.n.ID))
		for _, v := range n.n.Enumerants {
			if v.Name == v.Value {
				e.linef(indent+1, "%s @%d;", v.Name, v.Ordinal)
			} else {
				e.linef(indent+1, "%s @%d;  # %s", v.Name, v.Ordinal, quote(v.Value))
			}
		}
		e.linef(indent, "}")
		return
	}
	e.linef(indent, "struct %s @%s {", name, idText(n.n.ID))
	for _, f := range n.n.Fields {
		e.field(f, indent+1)
	}
	for _, c := range n.children {
		e.node(c, indent+1)
	}
	e.linef(indent, "}")
}

func (e *emitter) field(f *compiled.Field, indent int) {
	if f.Union == nil {
		def := ""
		if f.Default != nil && f.Form == compiled.Defaulted {
			if d, ok := e.defaultText(f.Type, *f.Default); ok {
				def = " = " + d
			}
		}
		e.linef(indent, "%s @%d :%s%s;", f.Name, f.Ordinal, e.typeText(f.Type), def)
		return
	}
	if f.Name == "" {
		e.linef(indent, "union {")
	} else {
		e.linef(indent, "%s :union {", f.Name)
	}
	for _, m := range f.Union {
		e.linef(indent+1, "%s @%d :%s;", m.Name, m.Ordinal, e.typeText(m.Type))
	}
	e.linef(indent, "}")
}

// typeText spells a type; a nested node by its simple name, which resolves
// from the struct declaring the field.
func (e *emitter) typeText(t *compiled.Type) string {
	if t == nil {
		return "Void"
	}
	switch t.Kind {
	case compiled.List:
		return "List(" + e.typeText(t.Elem) + ")"
	case compiled.Enum, compiled.Struct:
		n := e.c.Node(t.Node)
		return n.Name[strings.LastIndex(n.Name, ".")+1:]
	}
	return t.Kind.String()
}

// defaultText spells a default for a plain field, where capnp can declare
// one: Bool, integers, Text, Data and enums.
func (e *emitter) defaultText(t *compiled.Type, l lensir.Literal) (string, bool) {
	switch t.Kind {
	case compiled.Bool:
		return strconv.FormatBool(l.Bool), l.Kind == lensir.Bool
	case compiled.Int8, compiled.Int16, compiled.Int32, compiled.Int64,
		compiled.UInt8, compiled.UInt16, compiled.UInt32, compiled.UInt64:
		return l.Int, l.Kind == lensir.Int
	case compiled.Text:
		return quote(l.Str), l.Kind == lensir.String
	case compiled.Data:
		return `0x"` + hex.EncodeToString([]byte(l.Str)) + `"`, l.Kind == lensir.Bytes
	case compiled.Enum:
		if l.Kind != lensir.String {
			return "", false
		}
		for _, v := range e.c.Node(t.Node).Enumerants {
			if v.Value == l.Str {
				return v.Name, true
			}
		}
	}
	return "", false
}

func idText(id uint64) string {
	return fmt.Sprintf("0x%016x", id)
}

// quote spells s as a capnp text literal: double-quoted, with C escapes,
// and \x escapes for bytes outside printable ASCII.
func quote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch c {
		case '"', '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			if c < 0x20 || c >= 0x7f {
				fmt.Fprintf(&b, `\x%02x`, c)
			} else {
				b.WriteByte(c)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}
