// TypesFile is the name of the file [SchemaTypes] writes.
const TypesFile = "types.go"

// Syntax is a Go source file as a syntax tree. The Go types jennies emit their
// files as jenny trees of Syntax, so a pipeline can rewrite them with a
// jenny.TreeMapper[Syntax]; a tree renders gofmt-formatted.
type Syntax struct {
	Fset *token.FileSet
	File *ast.File
}

func renderSyntax(s Syntax) ([]byte, error) {
	var b bytes.Buffer
	if err := format.Node(&b, s.Fset, s.File); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

// TypeConfig governs the behavior of [SchemaTypes].
type TypeConfig struct {
	// PackageName is the name of the generated Go package. If empty, the
	// lowercase lineage name is used.
	PackageName string

	// RootName is the name of the Go type generated for the schema itself. If
	// empty, it is the lineage name with its first letter capitalized: Ship
	// for lineage "ship".
	//
	// Types generated for the schema's nested structs, enums and definitions
	// are named with RootName as their prefix.
	RootName string
}

// LineageTypeConfig governs the behavior of [LineageTypes].
type LineageTypeConfig struct {
	// RootName is the name of the Go type generated for each schema, as on
	// [TypeConfig.RootName]. Each version is a package of its own, so every
	// version's root type has the same name.
	RootName string
}

// SchemaTypes is a jenny that writes [TypesFile], declaring a type that the
// schema's instances can be decoded into, along with the types it needs: a
// named struct type for each nested struct, and a named string type with
// typed constants for each disjunction of strings.
//
// Optional fields are pointers (or nil-able maps, slices and interfaces) with
// `omitzero`, and `null | T` is a pointer to T. Constraints Go cannot express,
// such as bounds and regular expressions, are dropped to the base type; a
// scalar field's default is noted in its doc comment. A disjunction of
// structs, or of values of different kinds, is `any`. CUE's int is int64, and
// number is float64.
//
// The file is a jenny tree of [Syntax].
func SchemaTypes(cfg TypeConfig) jenny.Jenny[thema.Schema] {
	return schemaJennies.New("GoTypes", func(sch thema.Schema) (jenny.File, error) {
		pkg := cfg.PackageName
		if pkg == "" {
			pkg = strings.ToLower(sch.Lineage().Name())
		}
		root := rootFor(sch)
		if cfg.RootName != "" {
			root.Name = cfg.RootName
		}
		src, err := gotypes.Generate(gotypes.Config{
			PackageName: pkg,
			Header:      "// Code generated by thema. DO NOT EDIT.\n\n",
		}, root)
		if err != nil {
			return nil, err
		}
		fset := token.NewFileSet()
		f, err := parser.ParseFile(fset, TypesFile, src, parser.ParseComments)
		if err != nil {
			return nil, fmt.Errorf("generated Go for %s does not parse: %w", versionDir(sch), err)
		}
		return jenny.NewTree(TypesFile, Syntax{Fset: fset, File: f}, renderSyntax), nil
	})
}

// LineageTypes is a jenny that runs [SchemaTypes] for every schema in the
// lineage, and places each version's file in a directory and package of its
// own, named for the version: v0_0/types.go, in package v0_0, for version
// 0.0.
func LineageTypes(cfg LineageTypeConfig) jenny.Jenny[thema.Lineage] {
	lin := jenny.For[thema.Lineage](jenny.InputName(thema.Lineage.Name))
	return lin.Adapt(schemasOf,
		schemaJennies.PrefixBy(versionDir, SchemaTypes(TypeConfig{RootName: cfg.RootName})).Map(PackageFromDir),
	)
}

// PackageFromDir is a mapper that names the package of each Go file of
// [Syntax] after the directory the file is in, as [LineageTypes] does for each
// version. It fails for a file with no directory, or one whose directory is
// not a Go identifier, and passes every file that is not a tree of Syntax
// through unchanged.
var PackageFromDir = jenny.TreeMapper(func(f jenny.File, s Syntax) (Syntax, error) {
	pkg := path.Base(path.Dir(f.Path()))
	if !token.IsIdentifier(pkg) {
		return s, fmt.Errorf("%s: directory %q is not a Go package name", f.Path(), pkg)
	}
	file := *s.File
	name := *file.Name
	name.Name = pkg
	file.Name = &name
	return Syntax{Fset: s.Fset, File: &file}, nil
})

var schemaJennies = jenny.For[thema.Schema](jenny.InputName(versionDir))

func schemasOf(lin thema.Lineage) ([]thema.Schema, error) { return lin.All(), nil }

// versionDir names version X.Y vX_Y.
func versionDir(sch thema.Schema) string {
	v := sch.Version()
	return fmt.Sprintf("v%d_%d", v[0], v[1])
}

func rootFor(sch thema.Schema) gotypes.Root {
	lin := sch.Lineage()
	name := upperFirst(lin.Name())
	return gotypes.Root{
		Name:  name,
		Doc:   fmt.Sprintf("%s is version %s of the %s lineage's schema.", name, sch.Version(), lin.Name()),
		Value: sch.Underlying().LookupPath(cue.MakePath(cue.Hid("_schema", util.ThemaPackageID))),
	}
}

func upperFirst(s string) string {
	r, size := utf8.DecodeRuneInString(s)
	return string(unicode.ToUpper(r)) + s[size:]
}
