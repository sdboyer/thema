package gocode

import (
	"fmt"
	"strings"
	"unicode"
	"unicode/utf8"

	"cuelang.org/go/cue"
	"github.com/sdboyer/thema"
	"github.com/sdboyer/thema/internal/gotypes"
	"github.com/sdboyer/thema/internal/util"
)

// TypeConfig governs the behavior of [GenerateTypes] and [GenerateLineageTypes].
type TypeConfig struct {
	// PackageName is the name of the generated Go package. If empty, the
	// lowercase lineage name is used.
	PackageName string

	// RootName is the name of the Go type generated for the schema itself. If
	// empty, it is the lineage name with its first letter capitalized, followed
	// by the schema version: ShipV1_0 for version 1.0 of lineage "ship".
	//
	// Types generated for the schema's nested structs, enums and definitions
	// are named with RootName as their prefix. RootName is ignored by
	// [GenerateLineageTypes], which uses the default for every schema.
	RootName string
}

// GenerateTypes generates a formatted Go source file declaring a type that the
// provided Schema's instances can be decoded into, along with the types it
// needs: a named struct type for each nested struct, and a named string type
// with typed constants for each disjunction of strings.
//
// Optional fields are pointers (or nil-able maps, slices and interfaces) with
// `omitzero`, and `null | T` is a pointer to T. Constraints Go cannot express,
// such as bounds and regular expressions, are dropped to the base type; a
// scalar field's default is noted in its doc comment. A disjunction of
// structs, or of values of different kinds, is `any`. CUE's int is int64, and
// number is float64.
func GenerateTypes(sch thema.Schema, cfg *TypeConfig) ([]byte, error) {
	if cfg == nil {
		cfg = new(TypeConfig)
	}
	root := rootFor(sch)
	if cfg.RootName != "" {
		root.Name = cfg.RootName
	}
	return gotypes.Generate(goConfig(sch.Lineage(), cfg), root)
}

// GenerateLineageTypes is [GenerateTypes] for every schema in the lineage, in
// version order, in one Go file. Each schema's root type has the default name
// described on [TypeConfig.RootName], so the names of different versions do
// not collide.
func GenerateLineageTypes(lin thema.Lineage, cfg *TypeConfig) ([]byte, error) {
	if cfg == nil {
		cfg = new(TypeConfig)
	}
	var roots []gotypes.Root
	for _, sch := range lin.All() {
		roots = append(roots, rootFor(sch))
	}
	return gotypes.Generate(goConfig(lin, cfg), roots...)
}

func goConfig(lin thema.Lineage, cfg *TypeConfig) gotypes.Config {
	pkg := cfg.PackageName
	if pkg == "" {
		pkg = strings.ToLower(lin.Name())
	}
	return gotypes.Config{
		PackageName: pkg,
		Header:      "// Code generated by thema. DO NOT EDIT.\n\n",
	}
}

func rootFor(sch thema.Schema) gotypes.Root {
	lin := sch.Lineage()
	v := sch.Version()
	name := fmt.Sprintf("%sV%d_%d", upperFirst(lin.Name()), v[0], v[1])
	return gotypes.Root{
		Name:  name,
		Doc:   fmt.Sprintf("%s is version %s of the %s lineage's schema.", name, v, lin.Name()),
		Value: sch.Underlying().LookupPath(cue.MakePath(cue.Hid("_schema", util.ThemaPackageID))),
	}
}

func upperFirst(s string) string {
	r, size := utf8.DecodeRuneInString(s)
	return string(unicode.ToUpper(r)) + s[size:]
}
