// shipDir is the directory of the lineage the normal-form tests compile.
const shipDir = "ship"

// normalFormLineage is a lineage's directory, at dir: two frozen versions,
// the first importing a standard package, and a tip that adds a field the
// normal form must not hold.
func normalFormLineage(dir string) fstest.MapFS {
	file := func(s string) *fstest.MapFile { return &fstest.MapFile{Data: []byte(s)} }
	return fstest.MapFS{
		dir + "/history/0.0.thema": file("import \"strings\"\n\nSchema: {\n\tname: strings.MinRunes(1)\n}\n"),
		dir + "/history/0.1.thema": file("import \"strings\"\n\nSchema: {\n\tname:   strings.MinRunes(1)\n\tberth?: int\n}\n"),
		dir + "/tip.thema":         file("import \"strings\"\n\nSchema: {\n\tname:   strings.MinRunes(1)\n\tberth?: int\n\tcrew?:  int\n}\n"),
	}
}

// compileHistory compiles the history of the lineage in dir.
func compileHistory(t *testing.T, ctx *cue.Context, fsys fs.FS, dir string) *authoring.Compiled {
	t.Helper()
	name, files, err := authoring.Load(fsys, dir)
	if err != nil {
		t.Fatal(diag.Diagnostics(err))
	}
	c, err := authoring.Compile(ctx, name, files)
	if err != nil {
		t.Fatal(diag.Diagnostics(err))
	}
	return c
}

// NormalForm writes normalized.gen.cue: a generated header, a package named
// for the lineage importing thema and the history's standard packages, and
// thema.Lineage embedded beside the normal form of history/ alone.
func TestNormalForm(t *testing.T) {
	ctx := cuecontext.New()
	fs, err := authoring.NormalForm.GenerateFS(compileHistory(t, ctx, normalFormLineage(shipDir), shipDir))
	if err != nil {
		t.Fatal(err)
	}
	diagtest.CompareFS(t, "testdata/normalform/ship", fs)

	b, err := fs.ReadFile(authoring.NormalizedFile)
	if err != nil {
		t.Fatal(err)
	}
	if text := string(b); !strings.HasPrefix(text, "// Code generated by thema") || strings.Contains(text, "crew") {
		t.Errorf("%s is not the generated normal form of history/ alone:\n%s", authoring.NormalizedFile, text)
	}
}

// The tip is never part of the normal form: NormalForm refuses a lineage
// compiled with it.
func TestNormalFormRefusesTip(t *testing.T) {
	ctx := cuecontext.New()
	fsys := normalFormLineage(shipDir)
	name, files, err := authoring.Load(fsys, shipDir)
	if err != nil {
		t.Fatal(err)
	}
	c, err := authoring.CompileDevelopment(ctx, name, files)
	if err != nil {
		t.Fatal(diag.Diagnostics(err))
	}
	if _, err := authoring.NormalForm.Generate(c); err == nil {
		t.Error("NormalForm generated a lineage compiled with its tip")
	}
}

// A lineage named for a CUE keyword declares package for_.
func TestPackageName(t *testing.T) {
	for name, want := range map[string]string{shipDir: shipDir, "for": "for_", "let": "let_", "if": "if_", "string": "string"} {
		if got := authoring.PackageName(name); got != want {
			t.Errorf("PackageName(%q) = %q, want %q", name, got, want)
		}
	}
}

// Plain CUE imports a lineage by its directory's path, from its
// normalized.gen.cue alone, and what it imports binds to the versions the
// authoring form binds to, ID for ID. A lineage named for a keyword is
// imported with its package qualifier.
func TestNormalFormImports(t *testing.T) {
	ctx := cuecontext.New()
	rt := thema.NewRuntime(ctx)
	src := normalFormLineage("fleet/ship")
	for p, f := range normalFormLineage("fleet/for") {
		src[p] = f
	}

	mod := fstest.MapFS{
		"cue.mod/module.cue": {Data: []byte(util.ModuleFile("example.com/m"))},
		"use/use.cue": {Data: []byte(`package use

import (
	"example.com/m/fleet/ship"
	"example.com/m/fleet/for:for_"
)

flagship: ship
loop:     for_
moored:   ship.schemas["0"]["1"].schema & {name: "Bounty", berth: 3}
unnamed:  ship.schemas["0"]["0"].schema & {name: ""}
`)},
	}
	for _, dir := range []string{"fleet/ship", "fleet/for"} {
		fs, err := authoring.NormalForm.GenerateFS(compileHistory(t, ctx, src, dir))
		if err != nil {
			t.Fatal(err)
		}
		b, err := fs.ReadFile(authoring.NormalizedFile)
		if err != nil {
			t.Fatal(err)
		}
		mod[dir+"/"+authoring.NormalizedFile] = &fstest.MapFile{Data: b}
	}
	inst, err := load.InstanceWithThema(mod, "use", load.Package("use"))
	if err != nil {
		t.Fatal(err)
	}
	root := ctx.BuildInstance(inst)
	// unnamed is an error, by design; everything else evaluates.
	for _, field := range []string{"flagship", "loop"} {
		if err := root.LookupPath(cue.ParsePath(field)).Err(); err != nil {
			t.Fatalf("%s: %v", field, err)
		}
	}
	// A schema is a type: data that meets it is concrete, and data that does
	// not is an error.
	if err := root.LookupPath(cue.ParsePath("moored")).Validate(cue.Concrete(true)); err != nil {
		t.Errorf("data that meets imported schema 0.1: %v", err)
	}
	if err := root.LookupPath(cue.ParsePath("unnamed")).Validate(); err == nil {
		t.Error("an empty name meets imported schema 0.0, which constrains it with strings.MinRunes(1)")
	}

	for field, dir := range map[string]string{"flagship": "fleet/ship", "loop": "fleet/for"} {
		imported, err := thema.BindLineage(root, cue.MakePath(cue.Str(field)), rt)
		if err != nil {
			t.Fatalf("binding %s, imported from %s: %v", field, dir, diag.Diagnostics(err))
		}
		authored, err := load.AuthoringLineage(src, dir, rt)
		if err != nil {
			t.Fatal(diag.Diagnostics(err))
		}
		got, want := imported.All(), authored.All()
		if len(got) != len(want) {
			t.Fatalf("%s imports %d versions, and its history/ holds %d", dir, len(got), len(want))
		}
		for i := range want {
			gid, gerr := got[i].ID()
			wid, werr := want[i].ID()
			if gerr != nil || werr != nil || gid != wid {
				t.Errorf("%s version %s imports as ID %v (%v), and binds from history/ as %v (%v)", dir, want[i].Version(), gid, gerr, wid, werr)
			}
		}
	}
}
