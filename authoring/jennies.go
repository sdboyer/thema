var cuts = jenny.For[*Cut](jenny.InputName(func(c *Cut) string { return c.Version.String() }))

// FrozenVersion is a jenny that writes the version a cut froze,
// history/<major>.<minor>.thema, as [CutTip] made it. A clean cut froze
// nothing, and FrozenVersion writes nothing for it.
var FrozenVersion = cuts.New("FrozenVersion", func(c *Cut) (jenny.File, error) {
	for _, f := range c.Written {
		if f.Path != TipFile {
			return jenny.NewFile(f.Path, f.Text), nil
		}
	}
	return nil, nil
})

// CleanTip is a jenny that writes tip.thema as a cut leaves it: clean, its
// Schema alone. A clean cut changed nothing, and CleanTip writes nothing for
// it.
var CleanTip = cuts.New("CleanTip", func(c *Cut) (jenny.File, error) {
	for _, f := range c.Written {
		if f.Path == TipFile {
			return jenny.NewFile(f.Path, f.Text), nil
		}
	}
	return nil, nil
})

// DecompiledFiles is a jenny that writes the authoring files of a lineage in
// normal form, as [Decompile] recovers them: a version file under history/
// for each version, and a clean tip.thema. Paths are relative to the
// lineage's directory.
var DecompiledFiles = jenny.For[cue.Value](jenny.InputName(lineageName)).New("DecompiledFiles", func(lin cue.Value) (jenny.Files, error) {
	_, files, err := Decompile(lin)
	if err != nil {
		return nil, err
	}
	out := make(jenny.Files, 0, len(files))
	for _, f := range files {
		out = append(out, jenny.NewFile(f.Path, f.Text))
	}
	return out, nil
})

// InitialTip is a jenny that writes the tip.thema of a new lineage whose one
// version is the schema it is given, as [NewTip] does. A lineage of that tip
// alone has an empty history, and its tip cuts as 0.0.
var InitialTip = jenny.For[cue.Value]().New("InitialTip", func(schema cue.Value) (jenny.File, error) {
	tip, err := NewTip(schema)
	if err != nil {
		return nil, err
	}
	return jenny.NewFile(tip.Path, tip.Text), nil
})

// NormalizedFile is the lineage's normal form, beside its tip and history/,
// as [NormalForm] writes it: a generated CUE file that makes the lineage's
// directory a CUE package, so that plain CUE imports the lineage by its
// directory's path and uses its schemas as types, the way a .d.ts beside a
// .js lets TypeScript use JavaScript.
const NormalizedFile = "normalized.gen.cue"

// normalizedHeader opens every NormalizedFile. Its first line is in the form
// tools recognize as generated: // Code generated ... DO NOT EDIT.
const normalizedHeader = `// Code generated by thema from this lineage's history/. DO NOT EDIT.
//
// This is the lineage's normal form: every version under history/, compiled,
// and never the tip. Regenerate it with thema lineage compile.
`

// PackageName is the name of the CUE package a lineage's [NormalizedFile]
// declares: the lineage's name, so that the package is imported by its
// directory's path. A name that is a CUE keyword, such as for, if or let,
// cannot name a package, and gets a trailing underscore: a lineage named for
// is package for_, imported as "<module>/<path>/for:for_".
func PackageName(lineage string) string {
	if token.Lookup(lineage).IsKeyword() {
		return lineage + "_"
	}
	return lineage
}

// NormalForm is a jenny that writes [NormalizedFile] for a lineage compiled
// by [Compile] from its history: a CUE package named [PackageName] that
// imports thema's CUE module and is the lineage, thema.Lineage embedded
// beside its normal form. Importing the package gives the lineage as its
// value. The tip is never part of it, since what CUE imports is what was cut,
// which never changes: a lineage compiled with its tip, by
// [CompileDevelopment], is an error. The file is laid out as [Format] lays
// out the authoring form.
var NormalForm = jenny.For[*Compiled](jenny.InputName(func(c *Compiled) string { return c.Name })).New("NormalForm", func(c *Compiled) (jenny.File, error) {
	if v, ok := c.Provisional(); ok {
		return nil, diag.InternalErr(fmt.Errorf("%s was compiled with its tip, as %s; its %s is generated from its history alone, with Compile", c.Name, v, NormalizedFile))
	}
	// The normal form's nodes are positioned in the authoring files, which
	// would lay out the new file by their lines; it is parsed again from its
	// text, so that its positions are its own.
	text, err := c.Text()
	if err != nil {
		return nil, diag.InternalErr(fmt.Errorf("formatting the normal form of %s: %w", c.Name, err))
	}
	body, err := parser.ParseFile(NormalizedFile, text, parser.ParseComments)
	if err != nil {
		return nil, diag.InternalErr(fmt.Errorf("parsing the normal form of %s: %w", c.Name, err))
	}
	themaPath, _, _ := strings.Cut(util.ThemaModulePath, "@")
	imports := []string{strconv.Quote(themaPath)}
	var decls []ast.Decl
	for _, d := range body.Decls {
		if imp, ok := d.(*ast.ImportDecl); ok {
			for _, spec := range imp.Specs {
				imports = append(imports, spec.Path.Value)
			}
			continue
		}
		decls = append(decls, d)
	}
	slices.Sort(imports)
	body.Decls = decls
	rest, err := format.Node(body)
	if err != nil {
		return nil, diag.InternalErr(fmt.Errorf("formatting the normal form of %s: %w", c.Name, err))
	}
	var src strings.Builder
	fmt.Fprintf(&src, "%s\npackage %s\n\nimport (\n", normalizedHeader, PackageName(c.Name))
	for _, imp := range imports {
		fmt.Fprintf(&src, "\t%s\n", imp)
	}
	fmt.Fprintf(&src, ")\n\nthema.Lineage\n\n%s", rest)
	out, err := Format([]byte(src.String()))
	if err != nil {
		return nil, diag.InternalErr(fmt.Errorf("formatting the %s of %s: %w", NormalizedFile, c.Name, err))
	}
	return jenny.NewFile(NormalizedFile, out), nil
})

// Formatted is a mapper that lays out every version file, a file named
// *.thema, as [Format] does, and passes every other file through unchanged.
var Formatted = jenny.BytesMapper(func(f jenny.File, src []byte) ([]byte, error) {
	if path.Ext(f.Path()) != Ext {
		return src, nil
	}
	return Format(src)
})

// lineageName names a lineage in normal form by its name field, or by its
// path where it has none to read, as one built from source at its root has
// none.
func lineageName(lin cue.Value) string {
	if name, err := lin.LookupPath(cue.MakePath(cue.Str("name"))).String(); err == nil {
		return name
	}
	if p := lin.Path().String(); p != "" {
		return p
	}
	return "an unnamed lineage"
}
