// LineageFile is the lineage's normal form, beside its tip and history/: a
// CUE file that [GenerateLineageFile] writes and nobody edits. It makes the
// lineage's directory a CUE package that native CUE can import, the way a
// .d.ts beside a .js lets TypeScript use JavaScript. A collection's loaders
// check it ([CheckLineageFile]); a lineage loaded alone needs none.
const LineageFile = "lineage.cue"

// generatedHeader opens every generated LineageFile. Its first line is in the
// form tools recognize as generated: // Code generated ... DO NOT EDIT.
const generatedHeader = `// Code generated by thema from this lineage's history/. DO NOT EDIT.
//
// This is the lineage's normal form: every version under history/, compiled,
// and never the tip. Regenerate it with thema lineage compile.
`

// PackageName is the name of the CUE package a lineage's [LineageFile]
// declares: the lineage's name, which is its directory's, so that the
// package is imported by its directory's path. A name that is a CUE keyword
// (for, if, in, let, true, false, null, func) cannot name a package, and gets
// a trailing underscore: a lineage named for is package for_, imported as
// "<module>/<path>/for:for_".
func PackageName(lineage string) string {
	if token.Lookup(lineage).IsKeyword() {
		return lineage + "_"
	}
	return lineage
}

// GenerateLineageFile returns the text of the [LineageFile] of c, a lineage
// compiled by [Compile] from its history: a CUE package named [PackageName]
// that imports thema's CUE module and is the lineage, thema.Lineage unified
// with its normal form. Importing the package gives the lineage as its
// value. c must not include the tip: what native CUE imports is what was cut,
// and never changes.
func GenerateLineageFile(c *Compiled) ([]byte, error) {
	if v, ok := c.Provisional(); ok {
		return nil, diag.InternalErr(fmt.Errorf("%s was compiled with its tip, as %s; its %s is generated from its history alone, with Compile", c.Name, v, LineageFile))
	}
	if pkg := PackageName(c.Name); !ast.IsValidIdent(pkg) {
		return nil, diag.New(diag.E0137).
			Headlinef("the lineage's name is %q, which is not an identifier, so its %s cannot declare a package", c.Name, LineageFile).
			Help("a name starts with a letter and continues with letters and digits").Err()
	}
	// The normal form's nodes are positioned in the authoring files, which
	// would lay out the new file by their lines; it is parsed again from its
	// text, so that its positions are its own.
	text, err := c.Text()
	if err != nil {
		return nil, diag.InternalErr(fmt.Errorf("formatting the normal form of %s: %w", c.Name, err))
	}
	body, err := parser.ParseFile(LineageFile, text, parser.ParseComments)
	if err != nil {
		return nil, diag.InternalErr(fmt.Errorf("parsing the normal form of %s: %w", c.Name, err))
	}

	themaPath, _, _ := strings.Cut(util.ThemaModulePath, "@")
	imports := []string{strconv.Quote(themaPath)}
	var decls []ast.Decl
	for _, d := range body.Decls {
		if imp, ok := d.(*ast.ImportDecl); ok {
			for _, spec := range imp.Specs {
				imports = append(imports, spec.Path.Value)
			}
			continue
		}
		decls = append(decls, d)
	}
	slices.Sort(imports)
	body.Decls = decls
	rest, err := format.Node(body)
	if err != nil {
		return nil, diag.InternalErr(fmt.Errorf("formatting the normal form of %s: %w", c.Name, err))
	}
	var src strings.Builder
	fmt.Fprintf(&src, "%s\npackage %s\n\nimport (\n", generatedHeader, PackageName(c.Name))
	for _, imp := range imports {
		fmt.Fprintf(&src, "\t%s\n", imp)
	}
	fmt.Fprintf(&src, ")\n\nthema.Lineage\n\n%s", rest)
	// The authoring form's one layout, which keeps every struct's braces.
	out, err := Format([]byte(src.String()))
	if err != nil {
		return nil, diag.InternalErr(fmt.Errorf("formatting the %s of %s: %w", LineageFile, c.Name, err))
	}
	return out, nil
}

// CheckLineageFile checks that committed, the lineage's [LineageFile] as it
// is on disk, is what [GenerateLineageFile] writes for c; committed is nil
// when there is none. It returns nil when it is, and otherwise an E0151
// diagnostic that says what differs: the file is missing, it holds other
// versions than history/ does, or the first line where it differs.
func CheckLineageFile(c *Compiled, committed []byte) error {
	want, err := GenerateLineageFile(c)
	if err != nil {
		return err
	}
	help := fmt.Sprintf("regenerate it with thema lineage compile -l <the directory of %s>", c.Name)
	if committed == nil {
		return diag.New(diag.E0151).
			Headlinef("%s has no %s, the normal form of its history/", c.Name, LineageFile).
			Notef(token.NoPos, "a lineage of a collection keeps its normal form in %s, for native CUE to import", LineageFile).
			Help(help).Err()
	}
	if bytes.Equal(committed, want) {
		return nil
	}
	tf := token.NewFile(LineageFile, -1, len(committed))
	tf.SetLinesForContent(committed)
	b := diag.New(diag.E0151).Headlinef("%s is not the normal form of %s's history/", LineageFile, c.Name)
	have, haveOK := fileVersions(committed)
	gen, _ := fileVersions(want)
	if haveOK && !slices.Equal(have, gen) {
		b.At(tf.Pos(0, token.NoRelPos)).
			Notef(token.NoPos, "it holds versions %s, and history/ holds %s", strings.Join(have, ", "), strings.Join(gen, ", "))
	} else {
		line, haveLine, wantLine := firstDifference(committed, want)
		b.At(tf.Pos(lineOffset(committed, line), token.NoRelPos)).
			Notef(token.NoPos, "line %d is %s; generated from history/, it is %s", line+1, quoteLine(haveLine), quoteLine(wantLine))
	}
	return b.Note(token.NoPos, LineageFile+" is generated: an edit to it, or a change to history/ without regenerating it, makes it disagree with what thema binds").
		Help(help).Err()
}

// fileVersions returns the versions a LineageFile's schemas declare, as
// <major>.<minor>, read from its syntax: the file may be stale, or edited,
// and is not evaluated. ok is false when it does not parse.
func fileVersions(src []byte) (vs []string, ok bool) {
	f, err := parser.ParseFile(LineageFile, src)
	if err != nil {
		return nil, false
	}
	fields := func(x ast.Expr) []*ast.Field {
		var out []*ast.Field
		if s, ok := x.(*ast.StructLit); ok {
			for _, e := range s.Elts {
				if fd, ok := e.(*ast.Field); ok {
					out = append(out, fd)
				}
			}
		}
		return out
	}
	label := func(fd *ast.Field) string {
		l, _, _ := ast.LabelName(fd.Label)
		return l
	}
	for _, d := range f.Decls {
		fd, ok := d.(*ast.Field)
		if !ok || label(fd) != "schemas" {
			continue
		}
		for _, major := range fields(fd.Value) {
			for _, minor := range fields(major.Value) {
				vs = append(vs, label(major)+"."+label(minor))
			}
		}
	}
	return vs, true
}

// firstDifference returns the index of the first line where a and b differ,
// and that line of each ("" past its end).
func firstDifference(a, b []byte) (line int, la, lb string) {
	as, bs := strings.Split(string(a), "\n"), strings.Split(string(b), "\n")
	for i := 0; ; i++ {
		la, lb = "", ""
		if i < len(as) {
			la = as[i]
		}
		if i < len(bs) {
			lb = bs[i]
		}
		if la != lb || i >= len(as) || i >= len(bs) {
			return i, la, lb
		}
	}
}

// lineOffset returns the offset of the start of line (counted from 0) in src.
func lineOffset(src []byte, line int) int {
	off := 0
	for ; line > 0; line-- {
		i := bytes.IndexByte(src[off:], '\n')
		if i < 0 {
			return len(src)
		}
		off += i + 1
	}
	return off
}

func quoteLine(l string) string {
	if strings.TrimSpace(l) == "" {
		return "empty"
	}
	return "`" + strings.TrimSpace(l) + "`"
}
