// stringsV00 is a 0.0 that imports a builtin package, which lineage.cue
// imports beside thema.
const stringsV00 = "import \"strings\"\n\nSchema: {\n\tbefore: strings.MinRunes(1)\n}\n"

// compiled compiles the history of the lineage name from its version files,
// keyed by their paths beneath its directory.
func compiled(t *testing.T, name string, files map[string]string) *authoring.Compiled {
	t.Helper()
	fsys := fstest.MapFS{}
	for p, text := range files {
		fsys[name+"/"+p] = &fstest.MapFile{Data: []byte(text)}
	}
	_, fs, err := authoring.Load(fsys, name)
	if err != nil {
		t.Fatal(err)
	}
	c, err := authoring.Compile(cuecontext.New(), name, fs)
	if err != nil {
		t.Fatal(cerrors.Details(err, nil))
	}
	return c
}

func diagnostic(t *testing.T, err error, code diag.Code) diag.Diagnostic {
	t.Helper()
	ds := diag.Diagnostics(err)
	if len(ds) != 1 || ds[0].Code != code {
		t.Fatalf("got %v, want one %s", ds, code)
	}
	return ds[0]
}

func notes(d diag.Diagnostic) string {
	var b strings.Builder
	for _, n := range d.Notes {
		b.WriteString(n.Label + "\n")
	}
	return b.String()
}

// lineage.cue is generated, a package named for the lineage that imports
// thema and what the history imports, sorted, and embeds thema.Lineage; and
// it is formatted, so that it is the same on every run.
func TestGenerateLineageFile(t *testing.T) {
	c := compiled(t, "ship", map[string]string{"history/0.0.thema": stringsV00})
	got, err := authoring.GenerateLineageFile(c)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.HasPrefix(got, []byte("// Code generated by thema from this lineage's history/. DO NOT EDIT.\n")) {
		t.Errorf("lineage.cue does not open with the generated-file line:\n%s", got)
	}
	f, err := parser.ParseFile(authoring.LineageFile, got)
	if err != nil {
		t.Fatal(err)
	}
	if f.PackageName() != "ship" {
		t.Errorf("package %q, want ship", f.PackageName())
	}
	var imports []string
	for spec := range f.ImportSpecs() {
		imports = append(imports, spec.Path.Value)
	}
	if got, want := strings.Join(imports, " "), `"github.com/sdboyer/thema" "strings"`; got != want {
		t.Errorf("imports %s, want %s", got, want)
	}
	if !bytes.Contains(got, []byte("\nthema.Lineage\n")) {
		t.Errorf("lineage.cue does not embed thema.Lineage:\n%s", got)
	}
	formatted, err := authoring.Format(got)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, formatted) {
		t.Errorf("lineage.cue is not formatted:\n%s", got)
	}
	if err := authoring.CheckLineageFile(c, got); err != nil {
		t.Errorf("CheckLineageFile of what GenerateLineageFile wrote: %v", err)
	}
}

// A lineage named for a CUE keyword is a package with a trailing underscore.
func TestPackageName(t *testing.T) {
	for name, want := range map[string]string{"ship": "ship", "for": "for_", "null": "null_", "Ship2": "Ship2"} {
		if got := authoring.PackageName(name); got != want {
			t.Errorf("PackageName(%q) = %q, want %q", name, got, want)
		}
	}
	got, err := authoring.GenerateLineageFile(compiled(t, "for", map[string]string{"history/0.0.thema": v00}))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Contains(got, []byte("\npackage for_\n")) {
		t.Errorf("lineage.cue of for:\n%s", got)
	}
}

// What is not a lineage's history is refused: a name that cannot be a
// package, and a compilation that includes the tip.
func TestGenerateLineageFileRefuses(t *testing.T) {
	_, err := authoring.GenerateLineageFile(compiled(t, "tug-boat", map[string]string{"history/0.0.thema": v00}))
	diagnostic(t, err, diag.E0137)

	fsys := fstest.MapFS{
		"ship/history/0.0.thema": {Data: []byte(v00)},
		"ship/tip.thema":         {Data: []byte("Schema: {\n\tbefore: string\n\tafter?: string\n}\n")},
	}
	_, files, err := authoring.Load(fsys, "ship")
	if err != nil {
		t.Fatal(err)
	}
	c, err := authoring.CompileDevelopment(cuecontext.New(), "ship", files)
	if err != nil {
		t.Fatal(cerrors.Details(err, nil))
	}
	_, err = authoring.GenerateLineageFile(c)
	diagnostic(t, err, diag.E0901)
}

// CheckLineageFile says what differs: that there is no lineage.cue, that it
// holds other versions than history/, or the first line that differs.
func TestCheckLineageFile(t *testing.T) {
	old := compiled(t, "ship", map[string]string{"history/0.0.thema": v00})
	c := compiled(t, "ship", map[string]string{"history/0.0.thema": v00, "history/1.0.thema": v10})
	current, err := authoring.GenerateLineageFile(c)
	if err != nil {
		t.Fatal(err)
	}
	stale, err := authoring.GenerateLineageFile(old)
	if err != nil {
		t.Fatal(err)
	}
	edited := bytes.Replace(current, []byte("after: v0_0.before"), []byte("after: \"edited\""), 1)

	tests := map[string]struct {
		committed []byte
		headline  string
		note      string
		line      int
	}{
		"missing": {
			headline: "ship has no lineage.cue, the normal form of its history/",
			note:     "a lineage of a collection keeps its normal form in lineage.cue",
		},
		"stale": {
			committed: stale,
			headline:  "lineage.cue is not the normal form of ship's history/",
			note:      "it holds versions 0.0, and history/ holds 0.0, 1.0",
			line:      1,
		},
		"edited": {
			committed: edited,
			headline:  "lineage.cue is not the normal form of ship's history/",
			note:      "is `after: \"edited\"`; generated from history/, it is `after: v0_0.before`",
		},
	}
	for name, tt := range tests {
		t.Run(name, func(t *testing.T) {
			d := diagnostic(t, authoring.CheckLineageFile(c, tt.committed), diag.E0151)
			if d.Headline != tt.headline {
				t.Errorf("headline %q, want %q", d.Headline, tt.headline)
			}
			if !strings.Contains(notes(d), tt.note) {
				t.Errorf("notes %q, want %q", notes(d), tt.note)
			}
			if !strings.Contains(strings.Join(d.Help, "\n"), "thema lineage compile -l") {
				t.Errorf("help %q does not say how to regenerate", d.Help)
			}
			switch {
			case tt.committed == nil && d.Primary != nil:
				t.Errorf("a missing lineage.cue is positioned, at %+v", d.Primary)
			case tt.committed != nil && (d.Primary == nil || d.Primary.File != authoring.LineageFile):
				t.Errorf("positioned at %+v, want in lineage.cue", d.Primary)
			case tt.line != 0 && d.Primary.Line != tt.line:
				t.Errorf("at line %d, want %d", d.Primary.Line, tt.line)
			}
		})
	}
	if err := authoring.CheckLineageFile(c, current); err != nil {
		t.Errorf("the current lineage.cue: %v", err)
	}
}
