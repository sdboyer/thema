// A downstream wire format that refers to thema's types imports them from
// the package rather than declaring them: only those it refers to, by the
// names the package exports. Regenerate with THEMA_UPDATE_GOLDEN=1.
func TestGenerateImports(t *testing.T) {
	fl, err := Types.Generate(Config{
		Header:  "// Code generated by tsapi's tests. DO NOT EDIT.\n",
		Sources: []Source{{Package: "github.com/sdboyer/thema/playground/tsapi/internal/example"}},
		Import:  UIModule,
	})
	if err != nil {
		t.Fatal(err)
	}
	if len(fl) != 1 || fl[0].Path() != TypesFile {
		t.Fatalf("generated %v, want one %s", fl, TypesFile)
	}
	got, err := fl[0].Render()
	if err != nil {
		t.Fatal(err)
	}
	diagtest.CompareFile(t, "testdata/example.ts", string(got))
}

// Without Import, a reference to thema's types is left to TypeMappings, as
// for any other package.
func TestGenerateNoImport(t *testing.T) {
	got, err := render(Config{
		Sources: []Source{{Package: "github.com/sdboyer/thema/playground/tsapi/internal/example"}},
	})
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(got, "import") || !strings.Contains(got, "diag.Diagnostic") {
		t.Errorf("want diag.Diagnostic left as written and no import:\n%s", got)
	}
}

// A type both declared in the sources and imported would be declared twice.
func TestGenerateCollision(t *testing.T) {
	_, err := render(Config{
		Sources: []Source{{Package: "github.com/sdboyer/thema/playground/tsapi/internal/collide"}},
		Import:  UIModule,
	})
	if err == nil || !strings.Contains(err.Error(), "Diagnostic is declared in the sources and imported") {
		t.Fatalf("want a collision error, got %v", err)
	}
}

// UIConfig returns a copy: changing it changes neither later copies nor the
// types other Configs import.
func TestUIConfigCopies(t *testing.T) {
	var want []Source
	for _, src := range uiSources {
		want = append(want, Source{Package: src.Package, Files: append([]string(nil), src.Files...)})
	}
	c := UIConfig()
	for i := range c.Sources {
		for j := range c.Sources[i].Files {
			c.Sources[i].Files[j] = "changed.go"
		}
	}
	c.TypeMappings["diag.Diagnostic"] = "changed"
	c.Omit[0] = "changed"
	fresh := UIConfig()
	if !reflect.DeepEqual(fresh.Sources, want) || fresh.TypeMappings["diag.Diagnostic"] != "Diagnostic" || fresh.Omit[0] != "Vocabulary" {
		t.Errorf("changing one UIConfig changed the next:\n%+v", fresh)
	}
}
