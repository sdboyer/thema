// Package tsapi generates TypeScript declarations of JSON wire formats from
// the Go types that define them, as thema generates the wire types of
// @sdboyer/thema-ui (playground/components/src/types.ts).
//
// [Types] is a jenny that writes the file a [Config] describes. [UIConfig] is
// thema's own: the playground's requests and responses, diag's diagnostics
// and lacuna's translation lacunas. A program with a wire format of its own,
// such as a session API shaped like playground.Session, whose types embed or
// refer to thema's, runs Types on a Config of its own. Where its types refer
// to thema's, the generated file imports them from @sdboyer/thema-ui instead
// of declaring them again, so the program's types and the package's
// components agree on one declaration.
//
// tygo writes one TypeScript module per Go package; Types joins them into one
// self-contained file, referring to each type by its bare name. It loads the
// packages' sources, so it must run inside a module that can resolve them:
// thema's own, or one that requires it.
package tsapi

import (
	"fmt"
	"maps"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strings"

	"github.com/gzuidhof/tygo/tygo"
	"github.com/sdboyer/jenny"
)

// Source is a Go package whose types a wire format declares.
type Source struct {
	// Package is the package's import path.
	Package string
	// Files, if any, are the only files of the package whose types are
	// generated. Empty means all of them.
	Files []string
}

// Config says what Types writes.
type Config struct {
	// Header opens the generated file: typically a "Code generated" comment.
	Header string
	// Sources are the packages declaring the wire format, in the order the
	// generated file presents them.
	Sources []Source
	// TypeMappings name the TypeScript type that a Go type, written as its
	// source does (pkg.Type), becomes, as tygo's type_mappings do.
	TypeMappings map[string]string
	// Omit names types declared in Sources that the file leaves out, such as
	// Go interfaces declared beside the wire types, which are behavior and
	// which tygo renders as any.
	Omit []string
	// Import is the module specifier thema's wire types are imported from,
	// such as "@sdboyer/thema-ui". Where a type in Sources refers to one of
	// the types UIConfig declares, written as its package's name and the type
	// (diag.Diagnostic, lacuna.Lacuna, playground.File), the file imports it
	// from Import rather than declaring it. Empty means no type is imported.
	//
	// As tygo does for any type, an embedded thema type is rendered as a
	// field unless it is tagged tstype:",extends", which makes the interface
	// extend it, as JSON inlines its fields.
	Import string
}

// UIModule is the npm package that UIConfig's file is published in.
const UIModule = "@sdboyer/thema-ui"

// The packages and files thema's wire format is declared in, in the order
// the generated file presents them.
var uiSources = []Source{
	{"github.com/sdboyer/thema/playground", []string{"types.go"}},
	{"github.com/sdboyer/thema/diag", []string{"diag.go", "address.go"}},
	{"github.com/sdboyer/thema/lacuna", []string{"lacuna.go"}},
}

var uiConfig = Config{
	Header: `// Code generated by playground/tsapi from playground/types.go, diag and lacuna. DO NOT EDIT.
//
// The playground's wire format: what each operation of the wasm bridge takes
// and returns, as JSON.
`,
	Sources: uiSources,
	// The types one package refers to in another.
	TypeMappings: map[string]string{
		"diag.Diagnostic":           "Diagnostic",
		"lacuna.TranslationLacunas": "TranslationLacunas",
		"json.RawMessage":           "unknown",
	},
	Omit: []string{"Vocabulary", "Rewriter"},
}

// UIConfig returns the Config of thema's own wire types, the file published
// in @sdboyer/thema-ui as playground/components/src/types.ts.
func UIConfig() Config {
	cfg := uiConfig
	cfg.Sources = slices.Clone(uiSources)
	cfg.TypeMappings = maps.Clone(uiConfig.TypeMappings)
	cfg.Omit = slices.Clone(uiConfig.Omit)
	return cfg
}

// TypesFile is the name of the file [Types] writes.
const TypesFile = "types.ts"

// Types is a jenny that writes [TypesFile], declaring the types of a
// Config's Sources.
var Types = jenny.For[Config](jenny.InputName(configName)).New("TSWireTypes", func(cfg Config) (jenny.File, error) {
	src, err := render(cfg)
	if err != nil {
		return nil, err
	}
	return jenny.NewFile(TypesFile, []byte(src)), nil
})

// configName names a Config by the first package it declares types from.
func configName(cfg Config) string {
	if len(cfg.Sources) == 0 {
		return "no sources"
	}
	return cfg.Sources[0].Package
}

// tygoHeader matches the header tygo writes at the top of each module.
var tygoHeader = regexp.MustCompile(`(?m)\A(//[^\n]*\n)+\n*`)

// declared matches the name of each top-level declaration in a generated
// module.
var declared = regexp.MustCompile(`(?m)^export (?:interface|type|const|enum) (\w+)`)

// importMark prefixes, while generating, the name of a type to be imported,
// so that the types Sources refer to are told apart from same-named text.
const importMark = "__tsapi_import_"

var marked = regexp.MustCompile(importMark + `(\w+)`)

// render returns a TypeScript file declaring the types of cfg.Sources.
func render(cfg Config) (string, error) {
	mappings := map[string]string{}
	if cfg.Import != "" {
		modules, err := generate(uiSources, uiConfig.TypeMappings)
		if err != nil {
			return "", err
		}
		for i, src := range uiSources {
			name := src.Package[strings.LastIndex(src.Package, "/")+1:]
			for _, m := range declared.FindAllStringSubmatch(modules[i], -1) {
				mappings[name+"."+m[1]] = importMark + m[1]
			}
		}
	}
	for k, v := range cfg.TypeMappings {
		mappings[k] = v
	}

	modules, err := generate(cfg.Sources, mappings)
	if err != nil {
		return "", err
	}
	var body strings.Builder
	for i, src := range cfg.Sources {
		out := modules[i]
		for _, name := range cfg.Omit {
			out = omission(name).ReplaceAllString(out, "")
		}
		fmt.Fprintf(&body, "\n//////////\n// %s\n\n%s", src.Package, strings.TrimSpace(out)+"\n")
	}

	var imports []string
	for _, m := range marked.FindAllStringSubmatch(body.String(), -1) {
		if !slices.Contains(imports, m[1]) {
			imports = append(imports, m[1])
		}
	}
	for _, m := range declared.FindAllStringSubmatch(body.String(), -1) {
		if slices.Contains(imports, m[1]) {
			return "", fmt.Errorf("%s is declared in the sources and imported from %s", m[1], cfg.Import)
		}
	}
	sort.Strings(imports)

	var b strings.Builder
	b.WriteString(cfg.Header)
	if len(imports) > 0 {
		fmt.Fprintf(&b, "\nimport type { %s } from %q;\n", strings.Join(imports, ", "), cfg.Import)
	}
	b.WriteString(marked.ReplaceAllString(body.String(), "$1"))
	return b.String(), nil
}

// omission matches the declaration of the type name, with its doc comment.
func omission(name string) *regexp.Regexp {
	return regexp.MustCompile(`(?s)/\*\*(?:[^*]|\*[^/])*\*/\nexport type ` + regexp.QuoteMeta(name) + ` =[^;]*;\n`)
}

// generate returns the module tygo writes for each source, without tygo's
// header.
func generate(sources []Source, mappings map[string]string) ([]string, error) {
	dir, err := os.MkdirTemp("", "tsapi")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(dir) //nolint:errcheck // a leftover temporary directory is harmless

	cfg := &tygo.Config{}
	for i, src := range sources {
		cfg.Packages = append(cfg.Packages, &tygo.PackageConfig{
			Path:         src.Package,
			OutputPath:   filepath.Join(dir, fmt.Sprintf("%d.ts", i)),
			IncludeFiles: src.Files,
			TypeMappings: mappings,
			Indent:       "  ",
		})
	}
	if err := tygo.New(cfg).Generate(); err != nil {
		return nil, fmt.Errorf("tygo: %w", err)
	}
	out := make([]string, len(sources))
	for i := range sources {
		b, err := os.ReadFile(filepath.Join(dir, fmt.Sprintf("%d.ts", i))) //nolint:gosec // a file tygo just wrote under dir
		if err != nil {
			return nil, err
		}
		out[i] = tygoHeader.ReplaceAllString(string(b), "")
	}
	return out, nil
}
