// fleet is a collection, in testdata/fleet: lineages that bind on both
// paths (ship, and boat, whose tip is a minor change), one that binds only on
// the normal path (dinghy, with no tip), ones that bind on neither (barge,
// whose history is broken; tug-boat, whose name is not an identifier; raft,
// whose version is not under history/), ones whose normalized.gen.cue is not
// the normal form of their history, so that they bind only on the
// development path (skiff, which has none; canoe, whose normalized.gen.cue is
// from before its 0.1), and what a collection does not read: a directory with
// no version files, a lineage beneath a subdirectory, and files beside the
// lineages.
//
// The normalized.gen.cue of boat, dinghy and ship are regenerated by
// TestFleetNormalizedFiles, with THEMA_UPDATE_GOLDEN=1; canoe's is stale on
// purpose, and is not.
func fleet() fs.FS {
	return os.DirFS("testdata")
}

// The fleet's lineages, and a version, as the load tests name them.
const (
	shipName    = "ship"
	boatName    = "boat"
	dinghyName  = "dinghy"
	canoeName   = "canoe"
	raftName    = "raft"
	skiffName   = "skiff"
	tugBoatName = "tug-boat"
	bargeName   = "barge"
	v00         = "0.0"
)

// current are the lineages of the fleet whose normalized.gen.cue is current.
var current = []string{boatName, dinghyName, shipName}

// codeSet returns the distinct codes of the diagnostics in err.
func codeSet(err error) []string {
	cs := codesOf(err)
	slices.Sort(cs)
	return slices.Compact(cs)
}

func keys[V any](m map[string]V) []string {
	var ks []string
	for k := range m {
		ks = append(ks, k)
	}
	slices.Sort(ks)
	return ks
}

// On the normal path, each lineage binds its history alone: a lineage without
// a tip binds, and one that fails is reported on its own, by name, without
// keeping the others from binding. A lineage whose normalized.gen.cue is
// missing or stale fails. Nothing that is not a lineage directly beneath the
// root is read.
func TestAuthoringCollection(t *testing.T) {
	c, err := AuthoringCollection(fleet(), "fleet", thema.NewRuntime(cuecontext.New()))
	if err != nil {
		t.Fatal(cerrors.Details(err, nil))
	}
	if got, want := keys(c.Lineages), current; !slices.Equal(got, want) {
		t.Errorf("bound %v, want %v", got, want)
	}
	if got, want := c.Names(), []string{bargeName, boatName, canoeName, dinghyName, raftName, shipName, skiffName, tugBoatName}; !slices.Equal(got, want) {
		t.Errorf("names %v, want %v", got, want)
	}
	for name, lin := range c.Lineages {
		if lin.Name() != name {
			t.Errorf("lineage %s is named %s", name, lin.Name())
		}
	}
	if got := versionsOf(c.Lineages[boatName]); !slices.Equal(got, []string{v00}) {
		t.Errorf("boat's versions are %v: the tip was read", got)
	}
	failed := map[string][]string{
		bargeName:   {"E0215"},
		canoeName:   {"E0151"},
		raftName:    {"E0148"},
		skiffName:   {"E0151"},
		tugBoatName: {"E0137"},
	}
	if got := keys(c.Failed); !slices.Equal(got, keys(failed)) {
		t.Fatalf("failed %v, want %v", got, keys(failed))
	}
	for name, want := range failed {
		if got := codeSet(c.Failed[name]); !slices.Equal(got, want) {
			t.Errorf("%s failed with %v, want %v: %v", name, got, want, diag.Diagnostics(c.Failed[name]))
		}
	}
}

// On the development path, each lineage binds with its tip, provisional; a
// lineage without a tip fails, as it does alone. normalized.gen.cue is not
// read: it is the history's, and the development path binds the tip too.
func TestDevelopmentCollection(t *testing.T) {
	c, err := DevelopmentCollection(fleet(), "fleet", thema.NewRuntime(cuecontext.New()))
	if err != nil {
		t.Fatal(cerrors.Details(err, nil))
	}
	if got, want := keys(c.Lineages), []string{boatName, canoeName, shipName, skiffName}; !slices.Equal(got, want) {
		t.Errorf("bound %v, want %v", got, want)
	}
	boat := c.Lineages[boatName]
	if got := versionsOf(boat.Lineage); !slices.Equal(got, []string{v00, "0.1"}) {
		t.Errorf("boat's versions are %v, want its tip as 0.1", got)
	}
	if !boat.Provisional(thema.SV(0, 1)) || boat.Tip.String() != "tip (cuts as 0.1)" {
		t.Errorf("boat's tip is %v, want provisional at 0.1", boat.Tip)
	}
	if ship := c.Lineages[shipName]; !ship.Tip.Clean {
		t.Errorf("ship's tip is %v, want clean", ship.Tip)
	}
	failed := map[string][]string{
		bargeName:   {"E0215"},
		dinghyName:  {"E0149"},
		raftName:    {"E0148"},
		tugBoatName: {"E0137"},
	}
	if got := keys(c.Failed); !slices.Equal(got, keys(failed)) {
		t.Fatalf("failed %v, want %v", got, keys(failed))
	}
	for name, want := range failed {
		if got := codeSet(c.Failed[name]); !slices.Equal(got, want) {
			t.Errorf("%s failed with %v, want %v: %v", name, got, want, diag.Diagnostics(c.Failed[name]))
		}
	}
}

// A lineage's failure is positioned in its own files, by their paths within
// the FS the collection was loaded from.
func TestCollectionFailurePosition(t *testing.T) {
	c, err := AuthoringCollection(fleet(), "fleet", thema.NewRuntime(cuecontext.New()))
	if err != nil {
		t.Fatal(cerrors.Details(err, nil))
	}
	ds := diag.Diagnostics(c.Failed[bargeName])
	if len(ds) == 0 || ds[0].Primary == nil || ds[0].Primary.File != "fleet/barge/history/0.1.thema" {
		t.Errorf("barge's failure is %+v, want it at fleet/barge/history/0.1.thema", ds)
	}
}

// What keeps a directory from being read as a collection is the call's
// error, and there is no collection.
func TestCollectionRoot(t *testing.T) {
	tests := map[string]struct {
		root string
		want string
	}{
		"missing":    {root: "nope", want: "E0601"},
		"a file":     {root: "fleet/README.md", want: "E0623"},
		"a lineage":  {root: "fleet/ship", want: "E0624"},
		"no history": {root: "fleet/raft", want: "E0624"},
	}
	rt := thema.NewRuntime(cuecontext.New())
	for name, tt := range tests {
		t.Run(name, func(t *testing.T) {
			c, err := AuthoringCollection(fleet(), tt.root, rt)
			if c != nil || !slices.Equal(codesOf(err), []string{tt.want}) {
				t.Errorf("got %v, %v; want no collection and %s", c, codesOf(err), tt.want)
			}
			d, err := DevelopmentCollection(fleet(), tt.root, rt)
			if d != nil || !slices.Equal(codesOf(err), []string{tt.want}) {
				t.Errorf("on the development path, got %v, %v; want no collection and %s", d, codesOf(err), tt.want)
			}
		})
	}
}

// A collection with no lineages is empty, not an error.
func TestCollectionEmpty(t *testing.T) {
	c, err := AuthoringCollection(fleet(), "fleet/docs", thema.NewRuntime(cuecontext.New()))
	if err != nil {
		t.Fatal(err)
	}
	if len(c.Names()) != 0 {
		t.Errorf("an empty collection has %v", c.Names())
	}
}

// The normalized.gen.cue of each of the fleet's current lineages is what
// GenerateNormalizedFile writes for its history. With THEMA_UPDATE_GOLDEN=1
// they are rewritten.
func TestFleetNormalizedFiles(t *testing.T) {
	ctx := cuecontext.New()
	for _, name := range current {
		t.Run(name, func(t *testing.T) {
			dir := path.Join("fleet", name)
			_, files, err := authoring.Load(fleet(), dir)
			if err != nil {
				t.Fatal(err)
			}
			c, err := authoring.Compile(ctx, name, files)
			if err != nil {
				t.Fatal(err)
			}
			got, err := authoring.GenerateNormalizedFile(c)
			if err != nil {
				t.Fatal(err)
			}
			p := filepath.Join("testdata", "fleet", name, authoring.NormalizedFile)
			if envvars.UpdateGoldenFiles {
				if err = os.WriteFile(p, got, 0o600); err != nil {
					t.Fatal(err)
				}
				return
			}
			want, err := os.ReadFile(p) //nolint:gosec // a golden in testdata
			if err != nil {
				t.Fatal(err)
			}
			if diff := cmp.Diff(string(want), string(got)); diff != "" {
				t.Errorf("%s (-committed +generated):\n%s; run with %s=1", p, diff, envvars.VarUpdateGolden)
			}
		})
	}
}
