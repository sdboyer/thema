// Package tsapi generates the TypeScript declarations of the playground's
// wire format, playground/ui/src/api/types.ts, from the Go types that define
// it. Go is the source of truth; the file is generated, committed where the
// frontend imports it, and kept in lockstep by a test in the playground
// package.
//
// The wire format spans three packages: playground's requests and
// responses, diag's diagnostics and lacuna's translation lacunas. tygo
// writes one TypeScript module per Go package; Generate joins them into one
// self-contained file, referring to each type by its bare name.
package tsapi

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/gzuidhof/tygo/tygo"
)

// The packages and files the wire format is declared in, in the order the
// generated file presents them.
var sources = []struct {
	pkg   string
	files []string
}{
	{"github.com/sdboyer/thema/playground", []string{"types.go"}},
	{"github.com/sdboyer/thema/diag", []string{"diag.go", "address.go"}},
	{"github.com/sdboyer/thema/lacuna", []string{"lacuna.go"}},
}

// mappings name, in the joined file, the types one package refers to in
// another.
var mappings = map[string]string{
	"diag.Diagnostic":           "Diagnostic",
	"lacuna.TranslationLacunas": "TranslationLacunas",
	"json.RawMessage":           "unknown",
}

const header = `// Code generated by internal/tsapi from playground/types.go, diag and lacuna. DO NOT EDIT.
//
// The playground's wire format: what each operation of the wasm bridge takes
// and returns, as JSON.
`

// tygoHeader matches the header tygo writes at the top of each module.
var tygoHeader = regexp.MustCompile(`(?m)\A(//[^\n]*\n)+\n*`)

// omitted are Go interfaces declared beside the wire types: behavior, which
// tygo renders as any, not anything a response carries.
var omitted = regexp.MustCompile(`(?s)/\*\*(?:[^*]|\*[^/])*\*/\nexport type (?:Vocabulary|Rewriter) =[^;]*;\n`)

// Generate returns the contents of playground/ui/src/api/types.ts. It must
// run inside thema's module, since it loads the packages' sources.
func Generate() (string, error) {
	dir, err := os.MkdirTemp("", "tsapi")
	if err != nil {
		return "", err
	}
	defer os.RemoveAll(dir) //nolint:errcheck // a leftover temporary directory is harmless

	cfg := &tygo.Config{}
	for i, src := range sources {
		cfg.Packages = append(cfg.Packages, &tygo.PackageConfig{
			Path:         src.pkg,
			OutputPath:   filepath.Join(dir, fmt.Sprintf("%d.ts", i)),
			IncludeFiles: src.files,
			TypeMappings: mappings,
			Indent:       "  ",
		})
	}
	if err := tygo.New(cfg).Generate(); err != nil {
		return "", fmt.Errorf("tygo: %w", err)
	}

	var b strings.Builder
	b.WriteString(header)
	for i, src := range sources {
		out, err := os.ReadFile(filepath.Join(dir, fmt.Sprintf("%d.ts", i))) //nolint:gosec // a file tygo just wrote under dir
		if err != nil {
			return "", err
		}
		body := omitted.ReplaceAllString(tygoHeader.ReplaceAllString(string(out), ""), "")
		fmt.Fprintf(&b, "\n//////////\n// %s\n\n%s", src.pkg, strings.TrimSpace(body)+"\n")
	}
	return b.String(), nil
}
