package jsonschema

// This file holds what replaces the packages under cuelang.org/go/internal
// that upstream imports, which Go forbids importing from another module, and
// what the decoder uses from upstream's encoder files, which are not copied.

import (
	"strings"
	"unicode/utf8"

	"cuelang.org/go/cue"
	"cuelang.org/go/cue/ast"
)

// jsonSchemaTypeKinds is copied from upstream's generate.go.
//
// jsonSchemaTypeKinds maps each JSON Schema type to the CUE kind of the values
// it allows, the direction opposite to [cueKindToJSONSchemaTypes]. Note that
// number allows integers as well, so its kind subsumes that of integer.
var jsonSchemaTypeKinds = map[string]cue.Kind{
	"null":    cue.NullKind,
	"boolean": cue.BoolKind,
	"string":  cue.StringKind,
	"number":  cue.NumberKind,
	"integer": cue.IntKind,
	"object":  cue.StructKind,
	"array":   cue.ListKind,
}

// targetExperiments stands in for cuelang.org/go/internal/cueexperiment.File,
// holding the two experiments the decoder reads.
type targetExperiments struct {
	AliasV2   bool
	StructCmp bool
}

// currentExperiments are the experiments of the current language version,
// which upstream computes as cueexperiment.NewFile(cfg.TargetLanguageVersion)
// with TargetLanguageVersion empty, as encoding/openapi.Extract leaves it.
// The empty version is the current one, v0.18.0 at cuelang.org/go
// v0.18.0-rc.3 (cueversion.LanguageVersion), at which StructCmp (stable from
// v0.15.0) and AliasV2 (stable from v0.18.0) are both on. They are hard-coded
// so that the output stays the same as upstream's; the differential tests,
// here and in encoding/openapi, fail if they drift.
var currentExperiments = &targetExperiments{
	AliasV2:   true,
	StructCmp: true,
}

// NewComment is cuelang.org/go/internal.NewComment, copied.
//
// NewComment creates a new CommentGroup from the given text.
// Each line is prefixed with "//" and the last newline is removed.
// Useful for ASTs generated by code other than the CUE parser.
func NewComment(isDoc bool, s string) *ast.CommentGroup {
	if s == "" {
		return nil
	}
	cg := &ast.CommentGroup{Doc: isDoc}
	if !isDoc {
		cg.Line = true
		cg.Position = 10
	}
	addLine := func(text string) {
		cg.List = append(cg.List, &ast.Comment{Text: text})
	}
	// We only wrap a source line whose comment form would exceed wrapTrigger,
	// and then to wrapWidth; this leaves already sensibly wrapped text alone.
	const wrapWidth = 80
	const wrapTrigger = 100
	for line := range strings.Lines(s) {
		words := strings.Fields(line)
		joined := strings.Join(words, " ")
		switch {
		case len(words) == 0:
			addLine("//")
		case utf8.RuneCountInString(joined)+len("// ") <= wrapTrigger:
			addLine("// " + joined)
		default:
			// Too long; greedily wrap the words to wrapWidth.
			count := len("//")
			buf := strings.Builder{}
			buf.WriteString("//")
			for _, w := range words {
				n := utf8.RuneCountInString(w) + 1
				if count+n > wrapWidth && count > len("// ") {
					addLine(buf.String())
					buf.Reset()
					buf.WriteString("//")
					count = len("// ")
				}
				buf.WriteString(" ")
				buf.WriteString(w)
				count += n
			}
			addLine(buf.String())
		}
	}
	if last := len(cg.List) - 1; cg.List[last].Text == "//" {
		cg.List = cg.List[:last]
	}
	return cg
}
