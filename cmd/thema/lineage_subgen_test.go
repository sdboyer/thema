package main

import (
	"bytes"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	"github.com/sdboyer/thema/encoding/capnp/compiled"
)

const genCapnpLineage = `package x

import "github.com/sdboyer/thema"

lin: thema.Lineage & {
	name: "ship"
	schemas: {
		"0": "0": schema: {a: string}
		"0": "1": schema: {a: string, b?: int32}
	}
	lenses: "0.1->0.0": {
		v0_1: _
		v0_0: a: v0_1.a
	}
}
`

const genCapnpRejected = `package x

import "github.com/sdboyer/thema"

lin: thema.Lineage & {
	name: "unbounded"
	schemas: "0": "0": schema: {n: int}
}
`

// runGenCapnp runs `thema lineage gen capnp` against src in a fresh
// directory, re-executing this test binary as the CLI, and returns its
// combined output and exit error.
func runGenCapnp(t *testing.T, src string, args ...string) ([]byte, error) {
	t.Helper()
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "ship.cue"), []byte(src), 0o600); err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command(os.Args[0], append(strings.Fields("lineage gen capnp -l ship.cue -p lin --no-layout"), args...)...) //nolint:gosec // re-executes this test binary
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), runMainEnv+"=1")
	var out bytes.Buffer
	cmd.Stdout = &out
	cmd.Stderr = &out
	err := cmd.Run()
	return out.Bytes(), err
}

func TestGenCapnpSchema(t *testing.T) {
	out, err := runGenCapnp(t, genCapnpLineage)
	if err != nil {
		t.Fatalf("gen capnp failed: %v\n%s", err, out)
	}
	for _, want := range []string{"# Generated by thema from lineage ship.", "struct ShipV0 @0x", "a @1 :Text;", "b :union {"} {
		if !strings.Contains(string(out), want) {
			t.Errorf("schema output lacks %q:\n%s", want, out)
		}
	}
}

func TestGenCapnpArtifact(t *testing.T) {
	out, err := runGenCapnp(t, genCapnpLineage, "--format", "artifact", "--namespace", "example.com/m")
	if err != nil {
		t.Fatalf("gen capnp failed: %v\n%s", err, out)
	}
	c, err := compiled.Decode(out)
	if err != nil {
		t.Fatalf("decode artifact: %v", err)
	}
	if c.Lineage != "ship" || c.Namespace != "example.com/m" {
		t.Errorf("artifact names lineage %q in namespace %q", c.Lineage, c.Namespace)
	}
	if len(c.Versions) != 2 || len(c.Edges) != 1 || len(c.Checks) != 1 {
		t.Errorf("artifact has %d versions, %d edges and %d checks; want 2, 1 and 1", len(c.Versions), len(c.Edges), len(c.Checks))
	}
	if c.Layout != nil {
		t.Errorf("artifact carries a layout although --no-layout was given")
	}
}

func TestGenCapnpRejected(t *testing.T) {
	out, err := runGenCapnp(t, genCapnpRejected)
	if err == nil {
		t.Fatalf("gen capnp succeeded on a lineage capnp cannot carry:\n%s", out)
	}
	if !strings.Contains(string(out), "(rule int-unbounded)") {
		t.Errorf("rejection does not name its rule:\n%s", out)
	}
}
