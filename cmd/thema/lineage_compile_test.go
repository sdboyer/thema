// thema lineage compile writes normalized.gen.cue beside the lineage, which
// --check then finds up to date, and fails on once it is missing or changed.
func TestLineageCompile(t *testing.T) {
	dir := writeTipDir(t, minorTip)
	normal := filepath.Join(dir, authoring.NormalizedFile)
	compile := []string{lineageCmd, "compile", "-l", dir}
	check := slices.Concat(compile, []string{"--check"})

	_, errOut, err := runThema(t, dir, "", check...)
	if err == nil || !strings.Contains(errOut, "error[E0628]") || !strings.Contains(errOut, "is missing") {
		t.Errorf("--check with no %s: got %v, want E0628 missing:\n%s", authoring.NormalizedFile, err, errOut)
	}

	out, errOut, err := runThema(t, dir, "", compile...)
	if err != nil {
		t.Fatalf("%v\n%s", err, errOut)
	}
	if out != authoring.NormalizedFile+"\n" {
		t.Errorf("stdout: %q", out)
	}
	b, err := os.ReadFile(normal) //nolint:gosec // a file under t.TempDir()
	if err != nil {
		t.Fatal(err)
	}
	if text := string(b); !strings.HasPrefix(text, "// Code generated by thema") || !strings.Contains(text, "\npackage ship\n") {
		t.Errorf("%s:\n%s", authoring.NormalizedFile, text)
	}

	if _, cerrOut, cerr := runThema(t, dir, "", check...); cerr != nil {
		t.Errorf("--check of what compile just wrote: %v\n%s", cerr, cerrOut)
	}
	if err = os.WriteFile(normal, append(b, "// edited\n"...), 0o600); err != nil { //nolint:gosec // a file under t.TempDir()
		t.Fatal(err)
	}
	_, errOut, err = runThema(t, dir, "", check...)
	if err == nil || !strings.Contains(errOut, "error[E0628]") || !strings.Contains(errOut, "relative to -l") {
		t.Errorf("--check of an edited %s: got %v, want E0628 relative to -l:\n%s", authoring.NormalizedFile, err, errOut)
	}
}

// A history that does not bind has no normal form to write, and nothing is
// written.
func TestLineageCompileUnbound(t *testing.T) {
	dir := writeTipDir(t, cleanTip)
	// 0.1 changes name's type, which no minor version may.
	if err := os.WriteFile(filepath.Join(dir, "history", "0.1.thema"), []byte("Schema: {\n\tname: int\n}\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	_, errOut, err := runThema(t, dir, "", lineageCmd, "compile", "-l", dir)
	if err == nil || !strings.Contains(errOut, "error[E02") {
		t.Errorf("got %v, want a compatibility error:\n%s", err, errOut)
	}
	if _, err := os.Stat(filepath.Join(dir, authoring.NormalizedFile)); err == nil {
		t.Errorf("%s written for a history that does not bind", authoring.NormalizedFile)
	}
}
